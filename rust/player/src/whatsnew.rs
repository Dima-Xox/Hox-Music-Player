pub fn html() -> String {
    let mut h = String::from(
        "<html><body style='font-size:13px;'>",
    );
    for e in ENTRIES {
        h.push_str(&format!(
            "<h3 style='margin-bottom:2px;'>Версия {}</h3><ul>",
            e.version
        ));
        for it in e.items {
            h.push_str(&format!("<li>{}</li>", it));
        }
        h.push_str("</ul>");
    }
    h.push_str("</body></html>");
    h
}

/// Список изменений в виде [(версия, [пункты])] для отрисовки в egui.
pub fn items_of(version: &str) -> &'static [&'static str] {
    ENTRIES
        .iter()
        .find(|e| e.version == version)
        .map(|e| e.items)
        .unwrap_or(&[])
}
